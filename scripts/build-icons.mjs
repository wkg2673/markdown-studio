async function fetchIcon(candidates) {
  for (const name of candidates) {
    const url = BASE + name + '.svg';
    const res = await fetch(url);
    if (!res.ok) continue;
    const svg = await res.text();
    if (svg.includes('<svg')) return { svg, name };
  }
  throw new Error('No candidate resolved: ' + candidates.join(', '));
}

function normalize(svg) {
  return svg
    .replace(/<\?xml[^>]*\?>\s*/i, '')
    .replace(/<!DOCTYPE[^>]*>\s*/i, '')
    .replace(/\s*width="[^"]*"/i, '')
    .replace(/\s*height="[^"]*"/i, '')
    .replace(/\s*class="[^"]*"/i, '')
    .replace(/\s*stroke-width="[^"]*"/i, '')
    .replace(/\s*stroke-linecap="[^"]*"/i, '')
    .replace(/\s*stroke-linejoin="[^"]*"/i, '')
    .replace(/\s*\/>/g, '/>')
    .replace(/\s+/g, ' ')
    .replace(/\s*>\s*</g, '><')
    .replace(/<!--.*?-->/g, '')
    .trim();
}

const entries = [];
const resolved = {};
const failures = [];

for (const [key, candidates] of Object.entries(ICONS)) {
  try {
    const { svg, name } = await fetchIcon(candidates);
    resolved[key] = name;
    const js = normalize(svg).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
    entries.push(`  '${key}': '${js}'`);
  } catch (err) {
    failures.push(key + ' (' + err.message + ')');
  }
}

if (failures.length) {
  console.error('FAILED icons:\n' + failures.map((f) => '  - ' + f).join('\n'));
  process.exit(1);
}

const header = `/**
 * js/icons.js — generated by scripts/build-icons.mjs. Do not edit by hand.
 *
 * Inline Lucide icons (https://lucide.dev) so the app carries no icon
 * runtime dependency. Each value is a complete <svg> string (24x24,
 * stroke = currentColor). Icons render at the size of their container.
 *
 * Helper API (also exposed as window.icon):
 *   icon('bold')                       -> '<svg class="icon" ...>...</svg>'
 *   icon('bold', 'toolbar-btn-icon')   -> adds extra classes
 */
`;

const body = `const ICONS = {
${entries.join(',\n')}
};

function icon(name, extraClass) {
  const svg = ICONS[name];
  if (!svg) return '';
  const cls = extraClass ? 'icon ' + extraClass : 'icon';
  return svg.replace('<svg ', \`<svg class="\${cls}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" \`);
}

// Replace declarative <i data-icon="name"> elements with inline SVG and
// fill any other element carrying data-icon (buttons keep their own tag,
// so labels and ARIA attributes are preserved).
function hydrateIcons(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-icon]').forEach((el) => {
    const name = el.getAttribute('data-icon');
    const extra = el.getAttribute('data-icon-class') || '';
    const html = icon(name, extra);
    if (!html) return;
    if (el.tagName === 'I') el.outerHTML = html; // placeholder element is replaced
    else el.innerHTML = html;                   // container keeps its tag
  });
}

window.Icons = { icon, hydrateIcons, ICONS };
window.icon = icon;
`;

await writeFile(new URL('../js/icons.js', import.meta.url), header + body, 'utf8');
console.log('Built js/icons.js with ' + entries.length + ' icons:');
for (const [k, v] of Object.entries(resolved)) console.log('  ' + k.padEnd(16) + '<- ' + v);
