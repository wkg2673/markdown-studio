/**
 * Icon pipeline for Markdown Studio.
 *
 * Downloads the Lucide icons used by the app from the `lucide-static`
 * package and bundles them into `js/icons.js` so the app ships with
 * zero icon-related runtime dependencies (works fully offline).
 *
 * Usage:  node scripts/build-icons.mjs
 */
import { writeFile } from 'node:fs/promises';

const VERSION = '0.454.0';
const BASE = `https://unpkg.com/lucide-static@${VERSION}/icons/`;

/**
 * Logical icon name -> list of candidate file names in lucide-static.
 * Lucide occasionally renames icons; the first candidate that resolves wins.
 */
